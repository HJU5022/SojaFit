-- 부품 사양 표: 데이터시트 표 행 청크에서 규칙으로 뽑은 숫자 사양과 패키지 이름(db/schema/table-definition.md 5.7, ADR 0013).
-- 역할: 품번 하나의 사양 조회와 "조건에 맞는 부품 찾기"(backend/rag/spec_lookup.py)가 읽는 표. 적재는 `python -m backend.rag.pipeline.specs load`.
-- 하지 않는 일: 값 비교·판정(backend/judge/), parts 표 연결(parts 표가 아직 없어 품번 글자를 그대로 둔다), 데이터 적재.
-- [주의] Compose는 빈 볼륨에서만 이 파일을 자동 실행한다. 기존 DB(로컬 볼륨·Supabase)에는 따로 적용한다. 다시 실행해도 아무것도 바꾸지 않는다.
-- [주의] IF NOT EXISTS는 이미 있는 표의 정의가 같은지 검사하지 않는다.

CREATE TABLE IF NOT EXISTS part_specifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    part_number VARCHAR(100) NOT NULL,       -- [왜] parts 표가 없어 part_id 대신 데이터시트 표지의 품번 글자를 둔다
    document_id BIGINT NOT NULL,
    chunk_index INTEGER,                     -- 값이 나온 청크(document_chunks의 같은 문서·같은 순번). 패키지 행은 문서 단위라 NULL
    category VARCHAR(100),                   -- 다이오드 분류(예: schottky-rectifier, zener-diode). 후보 찾기 거르기용
    parameter_code VARCHAR(100) NOT NULL,
    symbol VARCHAR(50),
    minimum_value NUMERIC,
    typical_value NUMERIC,
    maximum_value NUMERIC,
    text_value TEXT,                         -- PACKAGE 행의 패키지 이름
    source_value_text TEXT NOT NULL,
    source_unit VARCHAR(30),
    normalized_unit VARCHAR(30),
    test_condition TEXT,
    page_number INTEGER,
    table_name VARCHAR(500),
    row_label VARCHAR(500),
    footnote_text TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_part_specifications PRIMARY KEY (id),
    -- [왜] 이 표는 청크에서 다시 만들 수 있는 파생 데이터라, 문서를 지우면 함께 지운다(다른 FK의 RESTRICT 규칙과 다름, 5.7)
    CONSTRAINT fk_part_specifications_document FOREIGN KEY (document_id) REFERENCES source_documents (id) ON DELETE CASCADE,
    -- 5.7·ADR 0013의 17개 + PACKAGE(표면 실장·스루홀 거르기용 패키지 이름)
    CONSTRAINT ck_part_specifications_parameter_code CHECK (parameter_code IN (
        'VRRM', 'IF_AV', 'IFSM', 'VF', 'IR', 'TRR', 'VZ', 'PD', 'CJ', 'TJ_MAX',
        'VR', 'VRWM', 'VBR', 'VC', 'IPP', 'PPPM', 'VESD', 'PACKAGE', 'AEC_Q101'
    )),
    CONSTRAINT ck_part_specifications_normalized_unit CHECK (
        normalized_unit IS NULL OR normalized_unit IN ('V', 'A', 's', 'W', 'F', 'degC')
    ),
    CONSTRAINT ck_part_specifications_has_value CHECK (
        minimum_value IS NOT NULL OR typical_value IS NOT NULL OR maximum_value IS NOT NULL OR text_value IS NOT NULL
    )
);
-- [왜] 품번 조회는 대소문자를 가리지 않는다(upper(part_number) = upper(입력)). 식 인덱스라야 이 비교가 인덱스를 쓴다
CREATE INDEX IF NOT EXISTS ix_part_specifications_part_upper ON part_specifications (upper(part_number));
CREATE INDEX IF NOT EXISTS ix_part_specifications_parameter_code ON part_specifications (parameter_code);
-- [왜] 적재가 문서 단위로 지우고 다시 넣는다(ADR 0007 증분)
CREATE INDEX IF NOT EXISTS ix_part_specifications_document ON part_specifications (document_id);
-- [왜] Supabase 기본 권한이 새 표를 anon·authenticated에 열어 둔다. 다른 public 표처럼 RLS를 켜고 정책을 두지 않아 공개 API로는 못 읽게 한다(표 주인인 서버 접속은 영향 없음, 11-05 운영 DB 확인)
ALTER TABLE part_specifications ENABLE ROW LEVEL SECURITY;
