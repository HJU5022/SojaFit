-- RAG 코퍼스 표: 출처 문서, 문서 청크, 청크 임베딩(docs/specs/rag-pipeline.md How, db/table-definition.md 5.4·5.6·5.15).
-- 문서·청크와 임베딩 테이블은 이 파일에서 생성하며 업무 테이블 초안이 참조한다.
-- IF NOT EXISTS는 기존 테이블의 정의가 동일한지 검증하지 않는다.
-- 000_init.sql 뒤에 실행된다. 기존 DB는 적용 이력과 구조를 확인하고 별도로 마이그레이션한다.

CREATE TABLE IF NOT EXISTS source_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document_key VARCHAR(200) NOT NULL,
    document_type VARCHAR(50) NOT NULL,
    title VARCHAR(500) NOT NULL,
    publisher VARCHAR(200) NOT NULL,
    source_url TEXT NOT NULL,
    revision VARCHAR(100),
    license_text TEXT,
    file_sha256 CHAR(64) NOT NULL,
    corpus_version VARCHAR(100) NOT NULL,
    collected_at TIMESTAMPTZ NOT NULL,
    parser VARCHAR(50) NOT NULL,
    chars_original INTEGER NOT NULL,
    chars_kept INTEGER NOT NULL,
    truncated BOOLEAN NOT NULL,
    retired_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_source_documents PRIMARY KEY (id),
    CONSTRAINT uq_source_documents_document_key UNIQUE (document_key),
    CONSTRAINT uq_source_documents_file_sha256 UNIQUE (file_sha256),
    CONSTRAINT ck_source_documents_type CHECK (document_type IN ('DATASHEET', 'PUBLIC_DOC')),
    CONSTRAINT ck_source_documents_chars_original CHECK (chars_original >= 0),
    CONSTRAINT ck_source_documents_chars_kept CHECK (chars_kept >= 0)
);

CREATE TABLE IF NOT EXISTS document_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document_id BIGINT NOT NULL,
    chunk_index INTEGER NOT NULL,
    content TEXT NOT NULL,
    chunk_sha256 CHAR(64) NOT NULL,
    page_number INTEGER,
    section_name VARCHAR(500),
    table_name VARCHAR(500),
    row_label VARCHAR(500),
    token_count INTEGER,
    chunker_version VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_document_chunks PRIMARY KEY (id),
    CONSTRAINT fk_document_chunks_document FOREIGN KEY (document_id) REFERENCES source_documents (id) ON DELETE RESTRICT,
    CONSTRAINT uq_document_chunks_document_index UNIQUE (document_id, chunk_index),
    CONSTRAINT ck_document_chunks_chunk_index CHECK (chunk_index >= 0),
    CONSTRAINT ck_document_chunks_page_number CHECK (page_number IS NULL OR page_number > 0),
    CONSTRAINT ck_document_chunks_token_count CHECK (token_count IS NULL OR token_count >= 0)
);
CREATE INDEX IF NOT EXISTS ix_document_chunks_chunk_sha256 ON document_chunks (chunk_sha256);

-- 임베딩 모델 text-embedding-3-small의 출력이 1536차원이다. 모델을 바꿔 차원이 달라지면 새 Migration으로 열을 바꾼다.
CREATE TABLE IF NOT EXISTS chunk_embeddings (
    chunk_id BIGINT NOT NULL,
    embedding_model VARCHAR(200) NOT NULL,
    embedding vector(1536) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_chunk_embeddings PRIMARY KEY (chunk_id, embedding_model),
    CONSTRAINT fk_chunk_embeddings_chunk FOREIGN KEY (chunk_id) REFERENCES document_chunks (id) ON DELETE RESTRICT
);
-- 거리 함수는 코사인 거리(table-definition 5.15). HNSW는 2,000차원까지 걸 수 있다.
-- [주의] 11-01 실측에서 이 인덱스(ef_search 1000, 그래프를 촘촘하게 해도)는 한국어 질문의 정확 검색 1위를 놓쳤다.
-- 그래서 backend/rag/retrieve.py는 인덱스를 끄고 정확 검색을 한다. 인덱스는 정의서(5.15)대로 두고, 쓸지는 사전 등록 실험으로 정한다
CREATE INDEX IF NOT EXISTS ix_chunk_embeddings_hnsw ON chunk_embeddings USING hnsw (embedding vector_cosine_ops);
