test('keeps project navigation, a compact result row and a larger conversation area', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/app?projectId=1&targetRef=D1')
  await expect(page.getByRole('button', { name: '정보 패널 펼치기' })).toBeVisible()
  await expect(page.getByRole('tablist', { name: '정보 보기' })).toHaveCount(0)
  await expect(page.getByRole('list', { name: '저장된 프로젝트' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '이전 대화' })).toBeVisible()
  await expect(page.getByLabel('사용 조건 (선택)', { exact: true })).toHaveCount(0)
  const send = page.getByRole('button', { name: '질문 전송', exact: true })
  await expect(send).toHaveText('')
  expect((await send.boundingBox())!.width).toBeLessThanOrEqual(40)
  await expect(page.getByRole('navigation', { name: '작업 메뉴' }).getByRole('button', { name: /^(프로젝트|회로|근거|후보 비교|승인·견적)$/ })).toHaveCount(0)
  await page.getByLabel('질문', { exact: true }).fill('D1을 SS34로 바꿔도 되나요?')
  await page.getByRole('button', { name: '질문 전송', exact: true }).click()
  const menu = page.getByRole('group', { name: '분석 결과 메뉴' })
  await expect(menu.getByRole('button')).toHaveCount(4)
  await menu.getByRole('button', { name: '문서 근거' }).click()
  await expect(page.getByText('SS34L SERIES_C2103.pdf', { exact: true })).toBeVisible()
  const stream = await page.locator('.conversation-stream').boundingBox()
  const composer = await page.locator('.composer').boundingBox()
  expect(stream!.height).toBeGreaterThan(composer!.height)
  const main = page.getByRole('main', { name: '분석 대화 작업면' })
  expect((await main.boundingBox())!.width).toBeGreaterThan(1440 * .55)
  expect((await page.getByRole('complementary', { name: '회로와 분석 정보' }).boundingBox())!.width).toBeLessThanOrEqual(380)
  for (const width of [1440, 1024, 768, 390]) {
    await page.setViewportSize({ width, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    const rows = await menu.getByRole('button').evaluateAll(buttons => new Set(buttons.map(button => button.getBoundingClientRect().y)).size)
    expect(rows).toBe(1)
    await expect.poll(async () => { const box = await page.locator('.composer').boundingBox(); return box!.y + box!.height }, { message: `${width}px composer stays in the viewport` }).toBeLessThanOrEqual(844)
    expect((await page.locator('.composer').boundingBox())!.height).toBeLessThan(150)
    await expect.poll(async () => (await page.locator('.conversation-stream').boundingBox())!.height / (await page.locator('.composer').boundingBox())!.height, { message: `${width}px messages are taller than the composer` }).toBeGreaterThan(1)
    if (width < 1200) {
      const before = (await main.boundingBox())!.width
      await menu.getByRole('button', { name: '문서 근거' }).click()
      await expect(page.getByRole('dialog', { name: '회로와 분석 정보' })).toBeVisible()
      await expect(page.getByText('SS34L SERIES_C2103.pdf', { exact: true })).toBeVisible()
      expect((await main.boundingBox())!.width).toBe(before)
      if (width === 1024) {
        await page.getByRole('tab', { name: '승인·견적' }).click()
        await page.getByLabel('승인할 후보').selectOption('0')
        await page.getByRole('button', { name: '판정 승인 확인' }).click()
        const confirmation = page.getByRole('dialog', { name: '판정 승인 확인' })
        await expect(confirmation).toBeVisible()
        await confirmation.getByRole('button', { name: '취소', exact: true }).press('Escape')
        await expect(confirmation).toHaveCount(0)
        await expect(page.getByRole('dialog', { name: '회로와 분석 정보' })).toBeVisible()
      }
      await page.getByRole('dialog', { name: '회로와 분석 정보' }).getByRole('button', { name: '닫기', exact: true }).press('Escape')
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await expect(menu.getByRole('button', { name: '문서 근거' })).toBeFocused()
    }
  }
  await page.setViewportSize({ width: 390, height: 650 })
  await expect.poll(async () => { const box = await page.locator('.composer').boundingBox(); return box!.y + box!.height }).toBeLessThanOrEqual(650)
  expect((await page.locator('.conversation-stream').boundingBox())!.height).toBeGreaterThan(150)
  await page.getByRole('button', { name: '작업 메뉴 펼치기' }).click()
  await page.getByRole('button', { name: '새 대화', exact: true }).click()
  await expect(menu).toHaveCount(0)
  await expect(page.getByLabel('질문', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: '작업 메뉴 펼치기' }).click()
  await page.getByRole('navigation', { name: '작업 메뉴' }).getByRole('button', { name: /D1을 SS34로 바꿔도 되나요/ }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('region', { name: '저장된 대화' })).toBeVisible()
  await page.getByRole('button', { name: '작업 메뉴 펼치기' }).click()
  const current = page.getByRole('list', { name: '이전 대화' }).getByRole('button', { name: /D1을 SS34로 바꿔도 되나요/ })
  await expect(current).toHaveAttribute('aria-current', 'true')
  await expect(current).toHaveAttribute('title', 'D1을 SS34로 바꿔도 되나요?')
  expect((await current.boundingBox())!.height).toBeLessThanOrEqual(34)
  expect(await current.locator('.workspace-session-title').evaluate(element => {
    const range = document.createRange(); range.selectNodeContents(element)
    return new Set([...range.getClientRects()].map(rect => rect.y)).size
  })).toBe(1)
  expect((await page.getByRole('button', { name: '새 대화', exact: true }).boundingBox())!.width).toBeLessThanOrEqual(32)
  await page.getByRole('dialog', { name: '프로젝트와 대화' }).getByRole('button', { name: '닫기', exact: true }).click()
  await expect(page.getByRole('article', { name: /사용자 메시지/ }).getByText('D1을 SS34로 바꿔도 되나요?', { exact: true })).toBeVisible()
  await page.getByRole('group', { name: '분석 결과 메뉴' }).getByRole('button', { name: '문서 근거' }).click()
  await expect(page.getByText('SS34L SERIES_C2103.pdf', { exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: '질문', exact: true })).toHaveCount(0)
})
