import { expect, test } from '@playwright/test'

test('shows the project-free landing and preserves its draft while opening project setup', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/app')
  await expect(page.getByRole('heading', { name: '회로에 맞는 대체 부품을 찾아보세요' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '회로 작업대' })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'SOJAFIT' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: '작업 메뉴' }).getByRole('button', { name: '계정' })).toHaveCount(0)
  await page.getByRole('button', { name: '사용자 0' }).click()
  await page.getByRole('menuitem', { name: '개인 설정' }).click()
  const settings = page.getByRole('dialog', { name: '개인 설정' })
  await expect(settings).toBeVisible()
  await settings.getByRole('checkbox', { name: '동작 효과 줄이기' }).check()
  await expect(page.locator('.workbench-shell')).toHaveClass(/motion-reduced/)
  await settings.getByRole('checkbox', { name: '동작 효과 줄이기' }).uncheck()
  await settings.getByRole('button', { name: '확인' }).click()
  await expect(page.locator('.landing-mark')).toContainText('SOJAFIT')
  await expect(page.getByText('회로 기반 부품 대체 분석')).toHaveCount(0)
  const landingBrand = await page.locator('.landing-mark').evaluate(element => {
    const icon = element.querySelector('svg')
    const label = element.querySelector('span')
    return {
      iconWidth: icon?.getBoundingClientRect().width ?? 0,
      labelSize: Number.parseFloat(label ? getComputedStyle(label).fontSize : '0'),
    }
  })
  expect(landingBrand.labelSize).toBeGreaterThanOrEqual(30)
  expect(landingBrand.iconWidth / landingBrand.labelSize).toBeCloseTo(2.2, 1)
  const suggestionLanes = page.locator('.suggestion-lane')
  await expect(suggestionLanes).toHaveCount(3)
  await expect(page.locator('.suggestion-group:not([aria-hidden="true"]) .suggestion-chip')).toHaveCount(30)
  const laneAnimations = await suggestionLanes.evaluateAll(elements => elements.map(element => getComputedStyle(element.querySelector('.suggestion-track')!).animationName))
  expect(laneAnimations).toEqual(['suggestions-left', 'suggestions-right', 'suggestions-left'])
  const suggestionColors = await page.locator('.suggestion-group:not([aria-hidden="true"]) .suggestion-chip').evaluateAll(elements => new Set(elements.map(element => getComputedStyle(element).borderColor)).size)
  expect(suggestionColors).toBeGreaterThanOrEqual(5)
  expect((await page.locator('.landing-suggestions').boundingBox())?.width).toBeGreaterThanOrEqual(1440)
  expect(await page.locator('.suggestion-chip').first().evaluate(element => Number.parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(13)
  await suggestionLanes.first().hover()
  const sourceSuggestions = page.locator('.suggestion-group:not([aria-hidden="true"]) .suggestion-chip')
  const visibleSuggestionIndex = await sourceSuggestions.evaluateAll(elements => elements.findIndex(element => {
    const box = element.getBoundingClientRect()
    return box.left > 230 && box.right < 1380 && box.top > 0 && box.bottom < 900
  }))
  expect(visibleSuggestionIndex).toBeGreaterThanOrEqual(0)
  const hoveredChip = sourceSuggestions.nth(visibleSuggestionIndex)
  await hoveredChip.hover()
  const hoveredSuggestion = await hoveredChip.evaluate(element => ({ background: getComputedStyle(element).backgroundColor, color: getComputedStyle(element).color, filter: getComputedStyle(element).filter }))
  expect(hoveredSuggestion.background).not.toBe('rgb(167, 216, 207)')
  expect(hoveredSuggestion.color).not.toBe('rgb(247, 250, 252)')
  expect(hoveredSuggestion.color).not.toBe(hoveredSuggestion.background)
  expect(hoveredSuggestion.filter).toBe('none')
  expect(await suggestionLanes.evaluateAll(elements => elements.map(element => getComputedStyle(element.querySelector('.suggestion-track')!).animationPlayState))).toEqual(['paused', 'running', 'running'])
  await page.mouse.move(0, 0)
  await expect.poll(() => page.locator('.landing-circuit').evaluate(element => getComputedStyle(element).backgroundImage)).not.toBe('none')
  await expect.poll(() => page.locator('.initial-landing').evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(23, 28, 34)')

  const question = page.getByRole('textbox', { name: '질문' })
  await question.fill('D1을 SS34L로 바꿔도 되나요?')
  await page.getByRole('button', { name: '사용 조건 추가(선택)' }).click()
  const conditions = page.getByRole('textbox', { name: '사용 조건 (선택)' })
  await conditions.fill('12V, 1A')
  await page.getByRole('button', { name: '분석 시작' }).click()
  await expect(page.getByRole('dialog', { name: '프로젝트 만들기' })).toBeVisible()
  await page.getByRole('button', { name: '닫기', exact: true }).click()
  await expect(question).toHaveValue('D1을 SS34L로 바꿔도 되나요?')
  await expect(conditions).toHaveValue('12V, 1A')

  const serviceHeading = page.getByRole('heading', { name: '회로 안에서 역할을 먼저 봅니다' })
  await serviceHeading.scrollIntoViewIfNeeded()
  await expect(serviceHeading).toBeInViewport()
  const firstFeature = page.locator('.service-feature').first()
  await expect.poll(() => firstFeature.evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(2)
  await page.getByRole('button', { name: '질문 입력하기' }).click()
  await expect(question).toBeFocused()

  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  expect((await page.locator('.landing-suggestions').boundingBox())?.width).toBeGreaterThanOrEqual(390)
  await expect.poll(() => firstFeature.evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(1)
  const rail = await page.getByRole('navigation', { name: '작업 메뉴' }).boundingBox()
  const actions = await page.locator('.landing-actions').boundingBox()
  expect((actions?.y ?? 0) + (actions?.height ?? 0)).toBeLessThanOrEqual(rail?.y ?? 0)
  const finalCta = page.locator('.landing-final-cta')
  await finalCta.scrollIntoViewIfNeeded()
  const finalBox = await finalCta.boundingBox()
  expect((finalBox?.y ?? 0) + (finalBox?.height ?? 0)).toBeLessThanOrEqual((rail?.y ?? 0) - 8)
})

test('keeps the information console usable at desktop and mobile sizes with reduced motion', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/app')
  await expect.poll(() => page.locator('.workbench-shell').evaluate(element => getComputedStyle(element).transitionProperty)).toContain('grid-template-columns')
  const analysis = page.getByRole('main', { name: '분석 대화 작업면' })
  const console = page.getByRole('complementary', { name: '회로와 분석 정보' })
  await expect(console).toBeVisible()
  const desktopAnalysis = await analysis.boundingBox()
  const desktopConsole = await console.boundingBox()
  expect(desktopAnalysis?.width).toBeGreaterThan(desktopConsole?.width ?? 0)
  await expect(page.getByRole('separator', { name: '회로 및 분석 정보 너비 조절' })).toBeVisible()
  await expect(page.getByRole('slider', { name: '정보 패널 너비' })).toHaveCount(0)

  await page.getByRole('button', { name: '작업 메뉴 접기' }).click()
  await page.waitForTimeout(280)
  const collapsedRail = await page.getByRole('navigation', { name: '작업 메뉴' }).boundingBox()
  const railButtons = page.locator('.function-rail > button:visible')
  for (let index = 0; index < await railButtons.count(); index += 1) {
    const button = await railButtons.nth(index).boundingBox()
    expect(button?.x).toBeGreaterThanOrEqual((collapsedRail?.x ?? 0) - 1)
    expect((button?.x ?? 0) + (button?.width ?? 0)).toBeLessThanOrEqual((collapsedRail?.x ?? 0) + (collapsedRail?.width ?? 0) + 1)
  }

  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  const mobileConsole = await console.boundingBox()
  expect(mobileConsole?.width).toBeLessThanOrEqual(390)
  const rail = await page.getByRole('navigation', { name: '작업 메뉴' }).boundingBox()
  expect(Math.round((rail?.y ?? 0) + (rail?.height ?? 0))).toBe(844)

  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: '프로젝트', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '내 프로젝트' })
  await expect(dialog).toBeVisible()
  expect(await dialog.evaluate(element => getComputedStyle(element).animationName)).toBe('none')
})

