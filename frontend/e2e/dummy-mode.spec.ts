import { expect, test } from '@playwright/test'

test('shows the approved public landing and keeps its preview usable on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /부품을 바꾸기 전에/ })).toBeVisible()
  await expect(page.getByRole('link', { name: '회로 검토 시작', exact: true })).toHaveAttribute('href', '/app')
  await page.getByRole('button', { name: /문서 근거/ }).click()
  await expect(page.getByRole('button', { name: /문서 근거/ })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByText('합성 예시 화면', { exact: true })).toBeVisible()
  for (const width of [1440, 1024, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    const logo = page.getByRole('img', { name: 'SOJAFIT', exact: true })
    await expect(logo).toBeVisible()
    await expect.poll(() => logo.evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
  }
  await page.getByRole('link', { name: '회로 검토 시작', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'SojaFit 에이전트' })).toBeVisible()
  await expect(page.getByRole('img', { name: 'SOJAFIT', exact: true })).toBeVisible()
  const icon = await page.request.get('/assets/sojafit-icon.svg')
  expect(icon.headers()['content-type']).toContain('image/svg+xml')
  expect(await icon.text()).toContain('SOJAFIT Circuit S')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

